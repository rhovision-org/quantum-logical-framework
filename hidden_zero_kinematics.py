#!/usr/bin/env python3
"""Hidden zeros on kinematics built from twists (issue #207, target G2c, round 2).

Part of the Quantum Logical Framework (QLF). Write-up: Hidden_Zeros_Closure.md §5.

Each spatial twist (axis a, sign s) carries the null momentum (1, s e_a); odd steps
are incoming kets, even steps outgoing bras. Conservation is ZFA balance of the
history with bras conjugated. X_ij = (p_i + ... + p_{j-1})^2 (Minkowski, +---).

Usage:
    python3 hidden_zero_kinematics.py --max-n 8
"""
from __future__ import annotations

import argparse
import itertools
from fractions import Fraction

import curve_cover_census as cc
from hidden_zero_closures import diagonals, zero_conditions

TWISTS = [(a, s) for a in range(3) for s in (1, -1)]


def mom(t, eta):
    a, s = t
    v = [eta, 0, 0, 0]
    v[1 + a] = eta * s
    return v


def dot(u, v):
    return u[0] * v[0] - u[1] * v[1] - u[2] * v[2] - u[3] * v[3]


def balanced_histories(n):
    """Histories of length n with sum of p = 0, generated by meet in the middle."""
    half = n // 2
    for odd in itertools.product(TWISTS, repeat=half):
        s = [0, 0, 0]
        for a, sg in odd:
            s[a] += sg
        for even in itertools.product(TWISTS, repeat=half):
            e = [0, 0, 0]
            for a, sg in even:
                e[a] += sg
            if e == s:
                h = [None] * n
                h[0::2] = odd
                h[1::2] = even
                yield tuple(h)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--max-n', type=int, default=8)
    args = ap.parse_args()
    for n in range(4, args.max_n + 1, 2):
        diags = diagonals(n)
        tris = [tuple(sorted(t)) for t in cc.triangulations(list(range(1, n + 1)))]
        loci = [zero_conditions(i, j, n) for (i, j) in diags]
        total = singular = k1_bad = on_locus = k2_bad = zeros = off_locus_zeros = 0
        example = None
        for h in balanced_histories(n):
            total += 1
            p = [mom(t, 1 if k % 2 == 0 else -1) for k, t in enumerate(h)]
            P = [[0, 0, 0, 0]]
            for v in p:
                P.append([P[-1][m] + v[m] for m in range(4)])

            def Xv(i, j):
                d = [P[j - 1][m] - P[i - 1][m] for m in range(4)]
                return dot(d, d)
            X = {d: Xv(*d) for d in diags}
            if any(v == 0 for v in X.values()):
                singular += 1
                continue
            nx = lambda k: (k % n) + 1
            def Xf(i, j):
                i, j = min(i, j), max(i, j)
                if j - i <= 1 or (i == 1 and j == n):
                    return 0
                return X[(i, j)]
            c = {}
            for a in range(1, n + 1):
                for b in range(1, n + 1):
                    if a == b or nx(a) == b or nx(b) == a:
                        continue
                    c[(a, b)] = Xf(a, b) + Xf(nx(a), nx(b)) - Xf(a, nx(b)) - Xf(nx(a), b)
                    if c[(a, b)] != -2 * dot(p[a - 1], p[b - 1]):
                        k1_bad += 1
            A = sum(Fraction(1, 1) / Fraction(eval_prod(t, X)) for t in tris)
            on = any(all(c[(a, b)] == 0 for a, b in L) for L in loci)
            on_locus += on
            if on and A != 0:
                k2_bad += 1
            if A == 0:
                zeros += 1
                if not on:
                    off_locus_zeros += 1
                    if example is None:
                        example = h
        print(f'n={n}: {total} conserving histories, {singular} singular; '
              f'K1 mismatches {k1_bad}; on a hidden-zero locus {on_locus} (K2 nonzero: {k2_bad}); '
              f'zeros {zeros}, off every locus {off_locus_zeros}'
              + (f'; first off-locus zero {example}' if example else ''))


def eval_prod(t, X):
    p = 1
    for d in t:
        p *= X[d]
    return p


if __name__ == '__main__':
    main()
